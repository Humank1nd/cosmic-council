#!/usr/bin/env bash

# Dream Caesar workstation integration for the local AI stack.
# Source this from an interactive shell or from launcher scripts.

if [ -f "$HOME/.config/ai-dev/env.sh" ]; then
  # shellcheck disable=SC1090
  . "$HOME/.config/ai-dev/env.sh"
fi

export DREAM_CAESAR_ROOT="${DREAM_CAESAR_ROOT:-$HOME/dream-caesar}"
export DREAM_CAESAR_RUNTIME_ROOT="${DREAM_CAESAR_RUNTIME_ROOT:-${AI_STACK_ROOT:-/mnt/storage/AI}/apps/dream-caesar}"
export DREAM_CAESAR_DESKTOP_COUNCIL_ROOT="${DREAM_CAESAR_DESKTOP_COUNCIL_ROOT:-$DREAM_CAESAR_RUNTIME_ROOT/desktop-council}"
export DREAM_CAESAR_ARTIFACTS="${DREAM_CAESAR_ARTIFACTS:-$DREAM_CAESAR_DESKTOP_COUNCIL_ROOT/artifacts}"
export DREAM_CAESAR_ARTIFACT_ROOT="${DREAM_CAESAR_ARTIFACT_ROOT:-$DREAM_CAESAR_ARTIFACTS}"
export DREAM_CAESAR_HANDOFF_DIR="${DREAM_CAESAR_HANDOFF_DIR:-$DREAM_CAESAR_DESKTOP_COUNCIL_ROOT/handoffs}"
export DREAM_CAESAR_HANDOFF_ROOT="${DREAM_CAESAR_HANDOFF_ROOT:-$DREAM_CAESAR_HANDOFF_DIR}"
export DREAM_CAESAR_MAIL_ROOT="${DREAM_CAESAR_MAIL_ROOT:-$DREAM_CAESAR_DESKTOP_COUNCIL_ROOT/mail}"
export DREAM_CAESAR_ACTIVE_CANON_PATH="${DREAM_CAESAR_ACTIVE_CANON_PATH:-$DREAM_CAESAR_DESKTOP_COUNCIL_ROOT/active-canon.json}"
export DREAM_CAESAR_CACHE="${DREAM_CAESAR_CACHE:-$DREAM_CAESAR_RUNTIME_ROOT/cache}"
export DREAM_CAESAR_LOGS="${DREAM_CAESAR_LOGS:-$DREAM_CAESAR_RUNTIME_ROOT/logs}"
export DREAM_CAESAR_DB_DIR="${DREAM_CAESAR_DB_DIR:-$DREAM_CAESAR_RUNTIME_ROOT/data}"
