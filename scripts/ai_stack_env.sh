  "$DREAM_CAESAR_RUNTIME_ROOT" \
  "$DREAM_CAESAR_DESKTOP_COUNCIL_ROOT" \
  "$DREAM_CAESAR_ARTIFACTS" \
  "$DREAM_CAESAR_HANDOFF_DIR" \
  "$DREAM_CAESAR_MAIL_ROOT" \
  "$DREAM_CAESAR_CACHE" \
  "$DREAM_CAESAR_LOGS" \
  "$DREAM_CAESAR_DB_DIR" \
  "$DREAM_CAESAR_RECOVERY_ROOT"

export DATABASE_URL="${DATABASE_URL:-sqlite+aiosqlite:///$DREAM_CAESAR_DB_PATH}"
