import asyncio
import logging
from abc import ABC, abstractmethod
from typing import Dict, Any, Optional
from .ai_service import AIService, AIProvider, AIResponse
from .research_service import ResearchService, ResearchResult

# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class BaseEnterprise(ABC):
    """Base class for all enterprise agents."""
    
    def __init__(self, name: str, emoji: str, enterprise_type: str):
        self.name = name
        self.emoji = emoji
        self.enterprise_type = enterprise_type
        self.ai_service = AIService(AIProvider.MOCK)  # Start with mock, can be upgraded
        self.research_service = ResearchService()
        
        logger.info(f"🏢 {self.name} initialized with AI service")
    
    @abstractmethod
    async def process(self, problem: str, context: Dict[str, Any] = None) -> str:
        """Process a problem and return a solution."""
        pass
    
    def _build_context(self, problem: str, additional_context: Dict[str, Any] = None) -> Dict[str, Any]:
        """Build context for AI processing."""
        context = {
            "enterprise_type": self.enterprise_type,
            "enterprise_name": self.name,
            "problem": problem
        }
        
        if additional_context:
            context.update(additional_context)
        
        return context


class RedOwl(BaseEnterprise):
    """🔴 Red Owl - Research & Knowledge Gathering"""
    
    def __init__(self):
        super().__init__("Red Owl", "🔴🦉", "research")
    
    async def process(self, problem: str, context: Dict[str, Any] = None) -> str:
        """Research the problem and gather knowledge."""
        try:
            logger.info(f"🔍 {self.name} starting research for: {problem}")
            
            # Conduct real research
            async with self.research_service as research:
                research_results = await research.research_problem(problem, max_results=5)
                research_summary = await research.get_research_summary(research_results)
            
            # Build context for AI
            ai_context = self._build_context(problem, {
                "research_results": research_summary,
                "research_count": len(research_results)
            })
            
            # Generate AI response based on research
            ai_response = await self.ai_service.generate_response(
                f"Based on the following research findings, provide a comprehensive analysis and recommendations for: {problem}\n\nResearch:\n{research_summary}",
                ai_context
            )
            
            # Format the response
            response = f"{self.emoji} Research Analysis:\n\n"
            response += f"📊 Research conducted: {len(research_results)} sources analyzed\n"
            response += f"🎯 Confidence: {ai_response.confidence:.1%}\n\n"
            response += f"Key Findings:\n{ai_response.content}\n\n"
            response += f"Sources: {', '.join(ai_response.sources)}"
            
            logger.info(f"✅ {self.name} research complete")
            return response
            
        except Exception as e:
            logger.error(f"❌ {self.name} research failed: {e}")
            return f"{self.emoji} Research Error: Unable to complete research due to technical issues. Please try again."


